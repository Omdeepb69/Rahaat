router = APIRouter(prefix="/reports", tags=["reports"])


class OperatorReportRequest(BaseModel):
    """A report taken down by an operator. ``text`` is recorded verbatim."""

    model_config = ConfigDict(extra="forbid")

    disaster_id: uuid.UUID
    text: str = Field(min_length=1, max_length=5000)
    received_via: str = Field(default="phone_call")
    idempotency_key: uuid.UUID = Field(
        description="Generated by the client once per report; resubmitting the same key is safe"
    )
    caller_name: Optional[str] = Field(default=None, max_length=160)
    caller_contact: Optional[str] = Field(default=None, max_length=64)
    location_text: Optional[str] = Field(default=None, max_length=512)
    latitude: Optional[float] = Field(default=None, ge=-90, le=90)
    longitude: Optional[float] = Field(default=None, ge=-180, le=180)
    people_count: Optional[int] = Field(default=None, ge=1, le=100000)
    language_hint: Optional[str] = Field(default=None, pattern="^(ml|en|hi|kok)$")


class ReportSummary(BaseModel):
    id: uuid.UUID
    disaster_id: uuid.UUID
    channel: str
    received_via: Optional[str]
    received_at: datetime
    processing_status: str
    processing_error: Optional[str]
    original_text: Optional[str]
    original_language: Optional[str]
    language_source: Optional[str]
    translated_text: Optional[str]
    translation_provider: Optional[str]
    has_audio: bool
    caller_name: Optional[str]
    caller_contact: Optional[str]
    caller_details_redacted: bool
    incident_id: Optional[uuid.UUID]
    incident_reference: Optional[str]
    incident_status: Optional[str]
    entered_by: Optional[uuid.UUID]


class ProcessingRun(BaseModel):
    stage: str
    provider: str
    model: Optional[str]
    status: str
    duration_ms: Optional[float]
    confidence: Optional[float]
    error: Optional[str]
    details: dict[str, Any]
    created_at: datetime


class ReportDetail(ReportSummary):
    processing_runs: list[ProcessingRun]


class CreatedReportResponse(BaseModel):
    report: ReportSummary
    already_existed: bool
    incident_id: Optional[uuid.UUID]
    incident_reference: Optional[str]
    is_new_incident: bool
    duplicate_candidates: int
    location_candidates: int
    enrichment_pending: bool


class ChannelAccepted(BaseModel):
    report_id: uuid.UUID
    already_existed: bool
    processing_status: str


def _summary(row: dict[str, Any], *, pii: bool) -> ReportSummary:
    return ReportSummary(
        id=row["id"], disaster_id=row["disaster_id"], channel=row["source_type"],
        received_via=row["channel_reference"], received_at=row["received_at"],
        processing_status=row["processing_status"], processing_error=row["processing_error"],
        original_text=row["original_text"], original_language=row["original_language"],
        language_source=row["language_source"], translated_text=row["translated_text"],
        translation_provider=row["translation_provider"], has_audio=bool(row["has_audio"]),
        caller_name=row["caller_name"] if pii else None,
        caller_contact=row["caller_contact"] if pii else None,
        caller_details_redacted=not pii and bool(row["caller_name"] or row["caller_contact"]),
        incident_id=row["incident_id"], incident_reference=row["incident_reference"],
        incident_status=row["incident_status"], entered_by=row["created_by"],
    )


@router.post("", response_model=CreatedReportResponse, status_code=status.HTTP_201_CREATED,
             summary="Enter a report")
def create_report(
    body: OperatorReportRequest,
    actor: CurrentUser = Depends(require(Permission.REPORTS_CREATE)),
    session: Session = Depends(get_db),
    pipeline: ReportPipeline = Depends(get_pipeline),
) -> CreatedReportResponse:
    """Record a report and analyse it immediately.

    The response includes the incident it produced or was attached to, how many
    possible duplicates were found, and how many location candidates.
    """
    try:
        created = intake.create_operator_report(
            session,
            pipeline,
            data=intake.OperatorReportInput(
                disaster_id=body.disaster_id, text=body.text, received_via=body.received_via,
                idempotency_key=str(body.idempotency_key), caller_name=body.caller_name,
                caller_contact=body.caller_contact, location_text=body.location_text,
                latitude=body.latitude, longitude=body.longitude, people_count=body.people_count,
                language_hint=body.language_hint,
            ),
            actor_id=actor.id,
        )
    except LookupError as exc:
        raise HTTPException(status.HTTP_404_NOT_FOUND, str(exc)) from None
    except (intake.IntakeError, LocationError) as exc:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY, str(exc)) from None
    except ValueError as exc:
        raise HTTPException(status.HTTP_409_CONFLICT, str(exc)) from None

    row = intake.get_report_row(session, created.report.id)
    assert row is not None
    outcome = created.outcome
    return CreatedReportResponse(
        report=_summary(row, pii=actor.can(Permission.CALLER_PII_READ)),
        already_existed=created.already_existed,
        incident_id=row["incident_id"],
        incident_reference=row["incident_reference"],
        is_new_incident=bool(outcome and outcome.is_new_incident),
        duplicate_candidates=outcome.duplicate_candidates if outcome else 0,
        location_candidates=outcome.location_candidates if outcome else 0,
        enrichment_pending=row["processing_status"] == "pending_enrichment",
    )


def _accept(session: Session, submission) -> ChannelAccepted:
    try:
        report, existed = intake.store_channel_report(session, submission)
    except LookupError as exc:
        raise HTTPException(status.HTTP_404_NOT_FOUND, str(exc)) from None
    except ValueError as exc:
        raise HTTPException(status.HTTP_409_CONFLICT, str(exc)) from None
    return ChannelAccepted(
        report_id=report.id, already_existed=existed, processing_status=report.processing_status
    )


@router.post("/channels/sms", response_model=ChannelAccepted, status_code=status.HTTP_202_ACCEPTED,
             summary="Accept a report from an SMS gateway")
def submit_sms(
    payload: SMSPayload,
    _: CurrentUser = Depends(require(Permission.REPORTS_CREATE)),
    session: Session = Depends(get_db),
) -> ChannelAccepted:
    """For an authenticated gateway integration. The report is queued for analysis."""
    return _accept(session, SMSAdapter.to_submission(payload))


@router.post("/channels/radio", response_model=ChannelAccepted, status_code=status.HTTP_202_ACCEPTED,
             summary="Accept a report from a radio console")
def submit_radio(
    payload: RadioConsolePayload,
    _: CurrentUser = Depends(require(Permission.REPORTS_CREATE)),
    session: Session = Depends(get_db),
) -> ChannelAccepted:
    return _accept(session, RadioConsoleAdapter.to_submission(payload))


@router.get("", response_model=Page[ReportSummary], summary="List reports")
def list_reports(
    disaster_id: Optional[uuid.UUID] = Query(None),
    channel: Optional[str] = Query(None, description="Comma-separated channels"),
    processing_status: Optional[str] = Query(None, description="Comma-separated statuses"),
    incident_id: Optional[uuid.UUID] = Query(None),
    q: Optional[str] = Query(None, max_length=200),
    page: Pagination = Depends(),
    actor: CurrentUser = Depends(require(Permission.REPORTS_READ)),
    session: Session = Depends(get_db),
) -> Page[ReportSummary]:
    rows, total = intake.list_reports(
        session, disaster_id=disaster_id, channels=split_csv(channel),
        statuses=split_csv(processing_status), incident_id=incident_id, search=q,
        limit=page.limit, offset=page.offset,
    )
    pii = actor.can(Permission.CALLER_PII_READ)
    return Page(items=[_summary(r, pii=pii) for r in rows], total=total, limit=page.limit, offset=page.offset)


@router.get("/{report_id}", response_model=ReportDetail, summary="Get a report with its processing history")
def get_report(
    report_id: uuid.UUID,
    actor: CurrentUser = Depends(require(Permission.REPORTS_READ)),
    session: Session = Depends(get_db),
) -> ReportDetail:
    row = intake.get_report_row(session, report_id)
    if row is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Report not found")
    summary = _summary(row, pii=actor.can(Permission.CALLER_PII_READ))
    runs = [
        ProcessingRun(
            stage=r.stage, provider=r.provider, model=r.model, status=r.status,
            duration_ms=r.duration_ms, confidence=r.confidence, error=r.error,
            details=r.details or {}, created_at=r.created_at,
        )
        for r in intake.processing_runs(session, report_id)
    ]
    return ReportDetail(**summary.model_dump(), processing_runs=runs)


@router.get("/{report_id}/audio", summary="Play a report's recording", response_class=FileResponse)
def get_report_audio(
    report_id: uuid.UUID,
    _: CurrentUser = Depends(require(Permission.REPORTS_READ, Permission.CALLER_PII_READ)),
    session: Session = Depends(get_db),
    settings: Settings = Depends(get_settings),
) -> FileResponse:
    report = session.get(ReportModel, report_id)
    path = intake.audio_path(settings.audio_storage_dir, report) if report else None
    if path is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "No recording is stored for this report")
    return FileResponse(path, headers={"Cache-Control": "private, no-store"})
